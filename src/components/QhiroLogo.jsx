export default function QhiroLogo({
  variant = 'icon',
  theme = 'dark',
  wordmark = 'Qhiro',
  className = '',
  size,
  title = 'Qhiro',
  decorative = false,
}) {
  const colors = THEMES[theme] ?? THEMES.dark;
  const iconSize = size ?? (variant === 'full' ? 40 : 32);
  const classes = ['qhiro-logo', `qhiro-logo--${variant}`, className].filter(Boolean).join(' ');

  const mark = (
    <svg
      className="qhiro-logo__mark"
      viewBox={VIEWBOX}
      width={iconSize}
      height={(Number(iconSize) * 150) / 157}
      role={decorative ? 'presentation' : 'img'}
      aria-hidden={decorative ? true : undefined}
      aria-label={decorative ? undefined : title}
      focusable="false"
    >
      {!decorative && <title>{title}</title>}
      <QhiroMarkPaths ink={colors.ink} leaf={colors.leaf} />
    </svg>
  );

  if (variant === 'icon') {
    return <span className={classes}>{mark}</span>;
  }

  return (
    <span className={classes}>
      {mark}
      <span className="qhiro-logo__wordmark">{wordmark}</span>
    </span>
  );
}
